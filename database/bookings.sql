-- Sportify / PostgreSQL / database: sporttrent
-- Chạy PHẦN 1 trước khi triển khai WAR mới vì Hibernate dùng validate.
-- Không xóa/tạo lại database, không sửa bảng hoặc dữ liệu hiện có.

-- ==================== PHẦN 1: BẢNG ĐƠN ĐẶT SÂN ====================
BEGIN;

-- Extension đi kèm PostgreSQL, dùng cho ràng buộc chống lịch trùng theo field_id.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS public.bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id BIGINT NOT NULL,
    customer_name VARCHAR(100) NOT NULL,
    customer_phone VARCHAR(20),
    starts_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    total_price NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bookings_field
        FOREIGN KEY (field_id) REFERENCES public.sports_fields(field_id),
    CONSTRAINT ck_bookings_customer_name CHECK (BTRIM(customer_name) <> ''),
    CONSTRAINT ck_bookings_time CHECK (ends_at > starts_at AND starts_at::DATE = ends_at::DATE),
    CONSTRAINT ck_bookings_price CHECK (total_price > 0),
    CONSTRAINT ck_bookings_status CHECK (
        status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'COMPLETED', 'CANCELLED')
    ),
    -- Cho phép các yêu cầu PENDING trùng giờ; chỉ một đơn được xác nhận.
    -- Khoảng [) cho phép hai lịch sát nhau: 08:00–09:00 và 09:00–10:00.
    CONSTRAINT ex_bookings_confirmed_time EXCLUDE USING GIST (
        field_id WITH =,
        tsrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status IN ('CONFIRMED', 'COMPLETED'))
);

CREATE INDEX IF NOT EXISTS idx_bookings_field_created
    ON public.bookings (field_id, created_at DESC, booking_id DESC);

CREATE INDEX IF NOT EXISTS idx_bookings_field_status_start
    ON public.bookings (field_id, status, starts_at);

COMMIT;

-- ==================== PHẦN 2: ĐƠN MẪU (TÙY CHỌN) ====================
-- Chọn riêng phần này để chạy sau PHẦN 1 nếu cần kiểm thử.
-- Dữ liệu tên/SĐT dưới đây là dữ liệu minh họa.
-- Chỉ dùng sân ACTIVE của owner_id = 1, mở ít nhất 10 giờ/ngày.
-- Không có sân phù hợp thì không chèn. Chạy lại cùng ngày không chèn trùng.
-- Hai đơn đầu trùng giờ để thử xác nhận đơn đầu rồi chặn đơn còn lại.
BEGIN;

WITH selected_field AS (
    SELECT field_id, open_time, price_per_hour
    FROM public.sports_fields
    WHERE owner_id = 1 AND status = 'ACTIVE'
      AND close_time - open_time >= INTERVAL '10 hours'
    ORDER BY field_id
    LIMIT 1
), local_clock AS (
    SELECT CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Ho_Chi_Minh' AS local_now
), samples (sample_no, customer_name, customer_phone, status, day_offset, hour_offset, duration) AS (
    VALUES
        (1, 'Trần Gia Huy', '0901000001', 'PENDING', 1, INTERVAL '2 hours', INTERVAL '90 minutes'),
        (2, 'Lê Thu Trang', '0901000002', 'PENDING', 1, INTERVAL '150 minutes', INTERVAL '90 minutes'),
        (3, 'Phạm Hoàng Nam', '0901000003', 'PENDING', 1, INTERVAL '4 hours', INTERVAL '90 minutes'),
        (4, 'Nguyễn Quốc Bảo', '0901000004', 'CONFIRMED', 1, INTERVAL '7 hours', INTERVAL '90 minutes'),
        (5, 'Đỗ Minh Anh', '0901000005', 'COMPLETED', 0, INTERVAL '0 hours', INTERVAL '90 minutes'),
        (6, 'Vũ Khánh Linh', '0901000006', 'REJECTED', 0, INTERVAL '4 hours', INTERVAL '90 minutes')
), prepared AS (
    SELECT field.field_id, sample.customer_name, sample.customer_phone, sample.status,
           (clock.local_now::DATE + sample.day_offset
            - CASE WHEN sample.status = 'COMPLETED'
                        AND clock.local_now::TIME < field.open_time + sample.duration
                   THEN 1 ELSE 0 END)
               + field.open_time + sample.hour_offset AS starts_at,
           sample.duration,
           ROUND(field.price_per_hour * EXTRACT(EPOCH FROM sample.duration) / 3600, 2) AS total_price,
           clock.local_now - sample.sample_no * INTERVAL '1 minute' AS created_at
    FROM selected_field field CROSS JOIN samples sample CROSS JOIN local_clock clock
)
INSERT INTO public.bookings
    (field_id, customer_name, customer_phone, starts_at, ends_at, total_price, status, created_at, updated_at)
SELECT sample.field_id, sample.customer_name, sample.customer_phone,
       sample.starts_at, sample.starts_at + sample.duration, sample.total_price,
       sample.status, sample.created_at, sample.created_at
FROM prepared sample
WHERE NOT EXISTS (
    SELECT 1 FROM public.bookings existing
    WHERE existing.field_id = sample.field_id
      AND existing.customer_name = sample.customer_name
      AND existing.starts_at = sample.starts_at
      AND existing.ends_at = sample.starts_at + sample.duration
)
AND (sample.status NOT IN ('CONFIRMED', 'COMPLETED') OR NOT EXISTS (
    SELECT 1 FROM public.bookings existing
    WHERE existing.field_id = sample.field_id
      AND existing.status IN ('CONFIRMED', 'COMPLETED')
      AND existing.starts_at < sample.starts_at + sample.duration
      AND existing.ends_at > sample.starts_at
));

COMMIT;
